def build(out):
    doc = new_doc()
    title(doc, "本科毕业设计文献综述", 22)
    for label in ["论文题目：" + TITLE, "姓    名：", "学    号：", "专    业：智能科学与技术", "班    级：", "指导教师：", "学    院：未来技术学院"]:
        para(doc, label, indent=False, size=14)
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
    title(doc, TITLE + "文献综述", 15)
    body = []
    for h, ps in SECTIONS:
        heading(doc, h)
        for t in ps:
            if t.startswith("（") and len(t) < 30:
                heading(doc, t, 12)
            else:
                para(doc, t)
                body.append(t)
    heading(doc, "七、参考文献")
    refs(doc, REFS)
    doc.save(out)
    return count_cn(body)


